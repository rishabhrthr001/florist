
import cloudinary from "cloudinary";
import dotenv from "dotenv";
import mongoose from "mongoose";

dotenv.config();

// Configure Cloudinary
cloudinary.v2.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY.trim(),
  api_secret: process.env.CLOUDINARY_API_SECRET.trim(),
});

const imagePath = "/Users/rishabhrathore/.gemini/antigravity/brain/0369984b-cab7-453c-b4f9-b350e6e8c3bb/media__1773235535101.jpg";

async function run() {
  try {
    console.log("Connecting to MongoDB...");
    await mongoose.connect(process.env.MONGO_URI);
    console.log("Connected to MongoDB");

    // Models
    const categorySchema = new mongoose.Schema({ name: String, slug: String });
    const Category = mongoose.models.Category || mongoose.model("Category", categorySchema);

    const productSchema = new mongoose.Schema({
      name: String,
      slug: String,
      description: String,
      images: [String],
      price: Number,
      categoryId: { type: mongoose.Schema.Types.ObjectId, ref: 'Category' },
      tags: [String],
      isActive: { type: Boolean, default: true },
      premiumWrapping: { type: Boolean, default: false }
    });
    const Product = mongoose.models.Product || mongoose.model("Product", productSchema);

    // 1. Upload to Cloudinary
    console.log("Uploading to Cloudinary...");
    const uploadRes = await cloudinary.v2.uploader.upload(imagePath, {
      folder: "products",
    });
    console.log("Uploaded:", uploadRes.secure_url);

    // 2. Get category
    const category = await Category.findOne({ slug: "flowers" });
    if (!category) throw new Error("Category 'flowers' not found");
    console.log("Found Category:", category.name, category._id);

    // 3. Create Product
    const productName = "Electric Blue & Royal Purple Orchid Symphony";
    let baseSlug = "electric-blue-royal-purple-orchid-symphony";
    let slug = baseSlug;
    const existing = await Product.findOne({ slug });
    if (existing) {
        slug += "-" + Math.floor(Math.random() * 1000);
    }
    
    const newProduct = new Product({
      name: productName,
      slug: slug,
      description: "A mesmerizing and avant-garde arrangement that challenges the traditional floral palette. This striking bouquet features multiple stems of vibrant electric blue and deep royal purple Dendrobium orchids. The cool, neon-like tones are perfectly contrasted against signature midnight-black premium hand-wrapping, creating a truly 'out of this world' presentation.\n\n**This Product Consists of**:\n- **Premium Orchids**: 10-12 Stems of vibrant electric blue and royal purple Dendrobium orchids.\n- **Packaging**: Signature midnight-black premium multi-layered parchment wrapping.\n- **Finishing**: Large vibrant magenta multi-layered ribbon bow.\n\n**Suitable for**: Modern celebrations, artistic birthdays, unique anniversaries, or for those who appreciate the extraordinary and the bold.",
      images: [uploadRes.secure_url],
      price: 1550,
      categoryId: category._id,
      tags: ["orchids", "blue orchids", "purple orchids", "luxury", "midnight", "bouquet", "vibrant", "modern"],
      isActive: true,
      premiumWrapping: true
    });

    const saved = await newProduct.save();
    console.log("Product saved successfully:", saved.name, "at Rs.", saved.price);

    process.exit(0);
  } catch (err) {
    console.error("Error:", err);
    process.exit(1);
  }
}

run();
