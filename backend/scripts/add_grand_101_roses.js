
import cloudinary from "cloudinary";
import dotenv from "dotenv";
import mongoose from "mongoose";

dotenv.config();

// Configure Cloudinary
cloudinary.v2.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY.trim(),
  api_secret: process.env.CLOUDINARY_API_SECRET.trim(),
});

const imagePath = "/Users/rishabhrathore/.gemini/antigravity/brain/0369984b-cab7-453c-b4f9-b350e6e8c3bb/media__1773226158952.jpg";

async function run() {
  try {
    console.log("Connecting to MongoDB...");
    await mongoose.connect(process.env.MONGO_URI);
    console.log("Connected to MongoDB");

    // Models
    const categorySchema = new mongoose.Schema({ name: String, slug: String });
    const Category = mongoose.models.Category || mongoose.model("Category", categorySchema);

    const productSchema = new mongoose.Schema({
      name: String,
      slug: String,
      description: String,
      images: [String],
      price: Number,
      categoryId: { type: mongoose.Schema.Types.ObjectId, ref: 'Category' },
      tags: [String],
      isActive: { type: Boolean, default: true },
      premiumWrapping: { type: Boolean, default: false }
    });
    const Product = mongoose.models.Product || mongoose.model("Product", productSchema);

    // 1. Upload to Cloudinary
    console.log("Uploading to Cloudinary...");
    const uploadRes = await cloudinary.v2.uploader.upload(imagePath, {
      folder: "products",
    });
    console.log("Uploaded:", uploadRes.secure_url);

    // 2. Get category
    const category = await Category.findOne({ slug: "flowers" });
    if (!category) throw new Error("Category 'flowers' not found");
    console.log("Found Category:", category.name, category._id);

    // 3. Create Product
    const productName = "Grand Desire 101 Red Rose Bouquet";
    let baseSlug = "grand-desire-101-red-rose-bouquet";
    let slug = baseSlug;
    const existing = await Product.findOne({ slug });
    if (existing) {
        slug += "-" + Math.floor(Math.random() * 1000);
    }
    
    const newProduct = new Product({
      name: productName,
      slug: slug,
      description: "The ultimate expression of deep, unconditional love. This magnificent arrangement features **101 premium, long-stemmed red roses**, meticulously hand-tied into a perfect, massive dome of velvet petals. Wrapped in layers of signature crimson red premium parchment and finished with a coordinated silk ribbon, this bouquet is designed to create an unforgettable moment of pure 'wow'.\n\n**This Grand Product Consists of**:\n- **Ultimate Luxury**: 101 Selected premium long-stemmed red roses.\n- **Packaging**: Multi-layered signature crimson red premium parchment wrapping.\n- **Finishing**: Luxury red silk ribbon bow and professional florist's tie.\n\n**Suitable for**: Marriage proposals, milestone anniversaries, grand romantic apologies, or making a once-in-a-lifetime impression.",
      images: [uploadRes.secure_url],
      price: 8500,
      categoryId: category._id,
      tags: ["red roses", "101 roses", "romantic", "grandeur", "luxury", "love", "anniversary", "proposal"],
      isActive: true,
      premiumWrapping: true
    });

    const saved = await newProduct.save();
    console.log("Product saved successfully:", saved.name, "at Rs.", saved.price);

    process.exit(0);
  } catch (err) {
    console.error("Error:", err);
    process.exit(1);
  }
}

run();
