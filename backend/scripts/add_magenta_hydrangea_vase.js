
import cloudinary from "cloudinary";
import dotenv from "dotenv";
import mongoose from "mongoose";

dotenv.config();

// Configure Cloudinary
cloudinary.v2.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY.trim(),
  api_secret: process.env.CLOUDINARY_API_SECRET.trim(),
});

const imagePath = "/Users/rishabhrathore/.gemini/antigravity/brain/0369984b-cab7-453c-b4f9-b350e6e8c3bb/media__1773229214289.jpg";

async function run() {
  try {
    console.log("Connecting to MongoDB...");
    await mongoose.connect(process.env.MONGO_URI);
    console.log("Connected to MongoDB");

    // Models
    const categorySchema = new mongoose.Schema({ name: String, slug: String });
    const Category = mongoose.models.Category || mongoose.model("Category", categorySchema);

    const productSchema = new mongoose.Schema({
      name: String,
      slug: String,
      description: String,
      images: [String],
      price: Number,
      categoryId: { type: mongoose.Schema.Types.ObjectId, ref: 'Category' },
      tags: [String],
      isActive: { type: Boolean, default: true },
      premiumWrapping: { type: Boolean, default: false }
    });
    const Product = mongoose.models.Product || mongoose.model("Product", productSchema);

    // 1. Upload to Cloudinary
    console.log("Uploading to Cloudinary...");
    const uploadRes = await cloudinary.v2.uploader.upload(imagePath, {
      folder: "products",
    });
    console.log("Uploaded:", uploadRes.secure_url);

    // 2. Get category
    const categoryName = "Flowers";
    const category = await Category.findOne({ slug: "flowers" });
    if (!category) throw new Error("Category 'flowers' not found");
    console.log("Found Category:", category.name, category._id);

    // 3. Create Product
    const productName = "Magenta Cloud Premium Hydrangea Vase";
    let baseSlug = "magenta-cloud-premium-hydrangea-vase";
    let slug = baseSlug;
    const existing = await Product.findOne({ slug });
    if (existing) {
        slug += "-" + Math.floor(Math.random() * 1000);
    }
    
    const newProduct = new Product({
      name: productName,
      slug: slug,
      description: "A breathtaking display of pure, saturated color. This premium arrangement features a massive, cloud-like cluster of deep magenta hydrangeas, known for their lush petals and incredible volume. Presented in a sleek, clear cylindrical glass vase to highlight the natural beauty of the stems.\n\n**This Product Consists of**:\n- **Premium Blooms**: 3-5 massive heads of premium magenta hydrangeas.\n- **Packaging**: Clear premium cylindrical glass vase (Included).\n- **Finishing**: Natural stem display within the water.\n\n**Suitable for**: Appreciation gifts, sophisticated home decor, office reception areas, or as a bold statement of gratitude and luxury.",
      images: [uploadRes.secure_url],
      price: 1850,
      categoryId: category._id,
      tags: ["hydrangea", "magenta", "pink", "vase", "luxury", "centerpiece", "bold", "modern"],
      isActive: true,
      premiumWrapping: false // Vase is the primary feature
    });

    const saved = await newProduct.save();
    console.log("Product saved successfully:", saved.name, "at Rs.", saved.price);

    process.exit(0);
  } catch (err) {
    console.error("Error:", err);
    process.exit(1);
  }
}

run();
